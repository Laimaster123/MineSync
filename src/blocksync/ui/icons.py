GRID = 12


def _rows(name: str) -> list[str]:
    return [line.strip() for line in PATTERNS[name].strip().splitlines()]


@cache
def pixmap(name: str, color: str, size: int = 24) -> QPixmap:
    """Значок name цвета color размером size×size (лучше кратно 12, чтобы пиксели были ровными)."""
    result = QPixmap(size, size)
    result.fill(Qt.GlobalColor.transparent)
    painter = QPainter(result)
    cell = size / GRID
    for y, row in enumerate(_rows(name)):
        for x, char in enumerate(row):
            if char == "#":
                painter.fillRect(
                    QRect(round(x * cell), round(y * cell), round((x + 1) * cell) - round(x * cell),
                          round((y + 1) * cell) - round(y * cell)),
                    QColor(color),
                )
    painter.end()
    return result


def icon(name: str, color: str, size: int = 24) -> QIcon:
    return QIcon(pixmap(name, color, size))


@cache
def flag(language: str, scale: int = 2) -> QPixmap:
    """Пиксельный флаг языка: "ru" — флаг России, "en" — флаг США. Сетка 18×12 «пикселей»."""
    width, height = 18, 12
    result = QPixmap(width * scale, height * scale)
    painter = QPainter(result)

    def cells(x: int, y: int, w: int, h: int, color: str) -> None:
        painter.fillRect(QRect(x * scale, y * scale, w * scale, h * scale), QColor(color))

    if language == "ru":
        cells(0, 0, width, 4, "#ffffff")
        cells(0, 4, width, 4, "#0039a6")
        cells(0, 8, width, 4, "#d52b1e")
    else:
        for stripe in range(height):
            cells(0, stripe, width, 1, "#b22234" if stripe % 2 == 0 else "#ffffff")
        cells(0, 0, 8, 6, "#3c3b6e")
        for y in range(1, 6, 2):
            for x in range(1, 8, 2):
                cells(x, y, 1, 1, "#ffffff")
    painter.end()
    return result
